//! Identifiers of the module and the opaque ids it holds from other modules (plain uuid, §1 rule 1).

use serde::{Deserialize, Serialize};
use uuid::Uuid;

macro_rules! uuid_id {
    ($(#[$meta:meta])* $name:ident) => {
        $(#[$meta])*
        #[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
        #[serde(transparent)]
        pub struct $name(Uuid);

        impl $name {
            pub const fn from_uuid(id: Uuid) -> Self {
                Self(id)
            }

            pub const fn as_uuid(&self) -> Uuid {
                self.0
            }
        }

        impl ::std::fmt::Display for $name {
            fn fmt(&self, f: &mut ::std::fmt::Formatter<'_>) -> ::std::fmt::Result {
                ::std::fmt::Display::fmt(&self.0, f)
            }
        }
    };
}

uuid_id!(
    /// A trading account (UUIDv7, generated by the Core).
    AccountId
);
uuid_id!(
    /// `catalog.opt_in_rule_version.id`.
    RuleVersionId
);
uuid_id!(
    /// gateway's platform account (ADR-0008): opaque here.
    VenueAccountId
);
uuid_id!(
    /// A paired adapter connection (identity).
    ConnectionId
);
uuid_id!(
    /// A preset version (catalog, S16).
    PresetVersionId
);
uuid_id!(
    /// A prop firm (catalog, S16).
    FirmId
);

impl AccountId {
    pub fn new_v7() -> Self {
        Self(Uuid::now_v7())
    }
}
