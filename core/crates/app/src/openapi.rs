//! The Core's own OpenAPI document, generated from handler annotations (`utoipa`) and
//! drift-checked against `contracts/http/openapi.bundled.yaml` (tests/openapi_drift.rs).
//!
//! Pattern for every module or adapter with HTTP handlers:
//! - annotate each handler with `#[utoipa::path(...)]`, using the contract's
//!   `operationId`, path, tag, parameters, bodies and responses; contract components
//!   are Rust types in `contracts::http` (handlers serialize the same types);
//! - expose `#[derive(utoipa::OpenApi)] #[openapi(paths(...))] pub struct <Name>Api;`
//!   next to the module's `pub fn router(...) -> axum::Router`;
//! - register both here and in [`crate::http::router`]: one `merge` line each.
//!
//! Conventions: `security(())` marks a public operation (OpenAPI `security: []`);
//! operations without it inherit the root `session` requirement.

use serde_json::Value;
use utoipa::OpenApi;
use utoipa::openapi::security::{ApiKey, ApiKeyValue, SecurityRequirement, SecurityScheme};

/// Root of the document: info, root security and security schemes.
#[derive(OpenApi)]
#[openapi(
    info(title = "All Win HTTP API", description = "Generated by the Core from its handlers."),
    security(("session" = []))
)]
struct CoreApi;

/// Component name of the embedded instruction schema (see `contracts::http::InstructionV1`).
const INSTRUCTION_COMPONENT: &str = "InstructionV1";

/// The generated document as `utoipa` models it (before contract-only post-processing).
pub fn openapi() -> utoipa::openapi::OpenApi {
    let mut doc = CoreApi::openapi();
    doc.merge(adapter_tradingview::IngressApi::openapi());
    doc.merge(identity_infra::http::IdentityApi::openapi());
    doc.merge(accounts_infra::http::AccountsApi::openapi());
    doc.merge(catalog_infra::rule_version_http::RuleVersionApi::openapi());
    add_security_schemes(&mut doc);
    mark_public_operations(&mut doc);
    doc
}

/// The generated document as JSON, with the instruction schema embedded byte-for-byte
/// from the contract file.
pub fn document() -> Result<Value, serde_json::Error> {
    let mut doc = serde_json::to_value(openapi())?;
    let instruction: Value = serde_json::from_str(contracts::instruction::v1::SCHEMA_JSON)?;
    if let Some(schemas) = doc
        .pointer_mut("/components/schemas")
        .and_then(Value::as_object_mut)
    {
        schemas.insert(INSTRUCTION_COMPONENT.to_owned(), instruction);
        // Contract components with if/then/not rules utoipa cannot model (accounts, S5).
        for (name, schema) in accounts_infra::http::schemas::raw_components()
            .into_iter()
            .chain(catalog_infra::rule_version_http::raw_components())
        {
            schemas.insert(name.to_owned(), schema);
        }
    }
    Ok(doc)
}

/// The contract's only scheme since HTTP 2.0.0 (passwordless: no `pendingSession`).
fn add_security_schemes(doc: &mut utoipa::openapi::OpenApi) {
    doc.components
        .get_or_insert_with(Default::default)
        .add_security_scheme(
            "session",
            SecurityScheme::ApiKey(ApiKey::Cookie(ApiKeyValue::new("__Host-aw_session"))),
        );
}

/// `utoipa` renders `security(())` as `[{}]` ("anonymous allowed"); the contract's
/// public operations use `[]` ("no requirement"). Every `[{}]` here means public.
fn mark_public_operations(doc: &mut utoipa::openapi::OpenApi) {
    let anonymous = SecurityRequirement::default();
    for item in doc.paths.paths.values_mut() {
        for op in operations_mut(item) {
            if op
                .security
                .as_ref()
                .is_some_and(|s| s.len() == 1 && s[0] == anonymous)
            {
                op.security = Some(Vec::new());
            }
        }
    }
}

fn operations_mut(
    item: &mut utoipa::openapi::PathItem,
) -> impl Iterator<Item = &mut utoipa::openapi::path::Operation> {
    [
        &mut item.get,
        &mut item.put,
        &mut item.post,
        &mut item.delete,
        &mut item.options,
        &mut item.head,
        &mut item.patch,
        &mut item.trace,
    ]
    .into_iter()
    .filter_map(Option::as_mut)
}
