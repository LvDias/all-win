# Bundler and structural self-check of the HTTP contract. Not a full OpenAPI validator.
#
# Layout: contracts/http/openapi.yaml is the root (info, servers, security, common components and one
# path-item `$ref` per module path); contracts/http/modules/<module>.yaml holds a module's `paths` and
# its own `components`. A module refers to root components as `../openapi.yaml#/components/...`, to its
# own as `#/components/...`, and to another module's as `<module>.yaml#/components/...`.
# The bundle (contracts/http/openapi.bundled.yaml, committed, never edited by hand) inlines the module
# path items and merges module components into the root namespace; component names are unique across
# the root and all modules. The Core's drift check and every check below run on the bundle.
#
# Checks (on the bundle):
# - the committed bundle matches the generated one (`--write` regenerates it);
# - no null values in any source file (root and modules; stray keys from unquoted commas);
# - module files hold only `paths` / `components`, and every module path is referenced by the root;
# - every $ref resolves (local pointers and external files);
# - operationIds are unique;
# - every schema is valid JSON Schema 2020-12: components and inline (parameters, headers, bodies);
# - every example validates against its schema (operations and components/responses);
# - contract conventions: root session security, 401 on session operations, 500 everywhere,
#   400 where there is input, 403 on state-changing /api/v1 operations and on x-step-up operations,
#   x-step-up values, ingress has no 400/401/403; no null values in the bundle either.
# Usage: python3 contracts/scripts/check_openapi.py contracts/http/openapi.yaml [--write]
import os
import sys

import yaml
from jsonschema import Draft202012Validator

ROOT_URI = 'https://allwin.app/contracts/http/openapi.yaml'
METHODS = ('get', 'put', 'post', 'patch', 'delete')
STATE_CHANGING = ('put', 'post', 'patch', 'delete')


BUNDLE_NAME = 'openapi.bundled.yaml'
BUNDLE_HEADER = ('# GENERATED by contracts/scripts/check_openapi.py --write from openapi.yaml and modules/*.yaml.\n'
                 '# Do not edit; edit the sources and regenerate.\n')
COMPONENT_KINDS = ('schemas', 'responses', 'parameters', 'headers', 'requestBodies', 'examples')


def bundle(root_path):
    """Inline module path items and merge module components into the root namespace."""
    base = os.path.dirname(os.path.abspath(root_path))
    root = yaml.safe_load(open(root_path))
    errs = []
    modules = {}  # absolute path -> parsed module
    used_paths = set()  # (module file, path key) referenced by the root

    def nulls(o, where, path=''):  # an unquoted ': ' or ', ' in a flow mapping yields a null value
        if isinstance(o, dict):
            for k, v in o.items():
                if v is None:
                    errs.append(f'{where}: null value at {path}/{k} (quote the text?)')
                nulls(v, where, f'{path}/{k}')
        elif isinstance(o, list):
            for i, v in enumerate(o):
                nulls(v, where, f'{path}/{i}')

    nulls(root, os.path.basename(root_path))

    def load(fp):
        if fp not in modules:
            m = yaml.safe_load(open(fp)) or {}
            nulls(m, os.path.relpath(fp, base))
            extra = set(m) - {'paths', 'components'}
            if extra:
                errs.append(f'{os.path.relpath(fp, base)}: unexpected top-level keys {sorted(extra)}')
            modules[fp] = m
        return modules[fp]

    def rewrite(o, here):
        """Rewrite refs inside content from file `here` so they are valid in the bundle (root dir)."""
        if isinstance(o, dict):
            if isinstance(o.get('$ref'), str):
                ref = o['$ref']
                file_part, _, pointer = ref.partition('#')
                target = os.path.normpath(os.path.join(os.path.dirname(here), file_part)) if file_part else here
                in_contract = target == os.path.abspath(root_path) or target in module_files
                if in_contract:
                    if not pointer.startswith('/components/'):
                        errs.append(f'{os.path.relpath(here, base)}: ref {ref} must point to /components/')
                    elif target != os.path.abspath(root_path):
                        load(target)
                    o = {**o, '$ref': '#' + pointer}
                elif file_part:  # other external file: rebase relative to the bundle
                    o = {**o, '$ref': os.path.relpath(target, base) + ('#' + pointer if pointer else '')}
            return {k: rewrite(v, here) for k, v in o.items()}
        if isinstance(o, list):
            return [rewrite(v, here) for v in o]
        return o

    mod_dir = os.path.join(base, 'modules')
    module_files = {os.path.join(mod_dir, f) for f in sorted(os.listdir(mod_dir))
                    if f.endswith('.yaml')} if os.path.isdir(mod_dir) else set()

    out = dict(root)
    paths = {}
    for key, item in (root.get('paths') or {}).items():
        ref = item.get('$ref') if isinstance(item, dict) else None
        file_part, _, pointer = (ref or '').partition('#')
        if ref and file_part:
            fp = os.path.normpath(os.path.join(base, file_part))
            if fp not in module_files:
                errs.append(f'paths {key}: {ref} is not a modules/*.yaml file')
                continue
            if len(item) != 1:
                errs.append(f'paths {key}: a module path item ref takes no sibling keys')
            m = load(fp)
            mkey = pointer.removeprefix('/paths/').replace('~1', '/').replace('~0', '~')
            if pointer != '/paths/' + key.replace('~', '~0').replace('/', '~1') or mkey not in (m.get('paths') or {}):
                errs.append(f'paths {key}: {ref} must point to the same path in the module')
                continue
            used_paths.add((fp, key))
            paths[key] = rewrite(m['paths'][key], fp)
        else:
            paths[key] = rewrite(item, os.path.abspath(root_path))
    out['paths'] = paths

    comps = {k: dict(v) for k, v in (root.get('components') or {}).items()}
    origin = {(kind, n): 'openapi.yaml' for kind, d in comps.items() for n in d}
    done = set()
    while set(modules) - done:  # loading a module may load others through its refs
        for fp in sorted(set(modules) - done):
            done.add(fp)
            rel = os.path.relpath(fp, base)
            for kind, d in (modules[fp].get('components') or {}).items():
                if kind not in COMPONENT_KINDS:
                    errs.append(f'{rel}: component kind {kind} not allowed in a module')
                    continue
                for n, v in d.items():
                    if (kind, n) in origin:
                        errs.append(f'{rel}: components/{kind}/{n} already defined in {origin[(kind, n)]}')
                        continue
                    origin[(kind, n)] = rel
                    comps.setdefault(kind, {})[n] = rewrite(v, fp)
    out['components'] = comps

    for fp in sorted(module_files):
        for key in (load(fp).get('paths') or {}):
            if (fp, key) not in used_paths:
                errs.append(f'{os.path.relpath(fp, base)}: path {key} is not referenced by the root')
    return out, errs


def dump_bundle(doc):
    return BUNDLE_HEADER + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=120)


def make_validator_factory(doc):
    root = {'components': doc['components']}
    try:  # jsonschema >= 4.18
        from referencing import Registry, Resource
        from referencing.jsonschema import DRAFT202012
        registry = Registry().with_resource(ROOT_URI, Resource(contents=root, specification=DRAFT202012))
        return lambda schema: Draft202012Validator({'$id': ROOT_URI, **schema}, registry=registry)
    except ImportError:  # older jsonschema: RefResolver is the only option and is not deprecated there
        from jsonschema import RefResolver
        resolver = RefResolver(ROOT_URI, root)
        return lambda schema: Draft202012Validator(schema, resolver=resolver)


def check_refs(doc, base, errs):
    def walk(o, path):
        if isinstance(o, dict):
            for k, v in o.items():
                if k == '$ref' and isinstance(v, str):
                    if v.startswith('#/'):
                        cur = doc
                        for part in v[2:].split('/'):
                            if not isinstance(cur, dict) or part not in cur:
                                errs.append(f'unresolved {v} at {path}')
                                break
                            cur = cur[part]
                    elif not os.path.exists(os.path.normpath(os.path.join(base, v.split('#')[0]))):
                        errs.append(f'missing file {v} at {path}')
                walk(v, f'{path}/{k}')
        elif isinstance(o, list):
            for i, v in enumerate(o):
                walk(v, f'{path}/{i}')
    walk(doc, '')


def resolve(doc, obj):
    """Follow a local $ref (responses, parameters) to the referenced object."""
    while isinstance(obj, dict) and '$ref' in obj and obj['$ref'].startswith('#/'):
        cur = doc
        for part in obj['$ref'][2:].split('/'):
            cur = cur[part]
        obj = cur
    return obj


def operations(doc):
    for pth, item in doc['paths'].items():
        for m in METHODS:
            if m in item:
                yield pth, m, item[m]


def main(p, write=False):
    base = os.path.dirname(os.path.abspath(p))
    doc, errs = bundle(p)
    text = dump_bundle(doc)
    bundle_path = os.path.join(base, BUNDLE_NAME)
    if write:
        with open(bundle_path, 'w') as f:
            f.write(text)
        print(f'wrote {os.path.relpath(bundle_path)}')
    elif not os.path.exists(bundle_path) or open(bundle_path).read() != text:
        errs.append(f'{BUNDLE_NAME} is out of date; run: python3 contracts/scripts/check_openapi.py {p} --write')
    doc = yaml.safe_load(text)  # check exactly what is committed
    if not str(doc.get('openapi', '')).startswith('3.1'):
        errs.append('openapi must be 3.1.x')
    check_refs(doc, base, errs)

    def find_nulls(o, path):  # an unquoted comma in a flow mapping yields a stray key with a null value
        if isinstance(o, dict):
            for k, v in o.items():
                if v is None:
                    errs.append(f'null value at {path}/{k} (quote the text?)')
                find_nulls(v, f'{path}/{k}')
        elif isinstance(o, list):
            for i, v in enumerate(o):
                find_nulls(v, f'{path}/{i}')
    find_nulls(doc, '')
    validator = make_validator_factory(doc)

    ops = list(operations(doc))
    ids = [op.get('operationId') for _, _, op in ops]
    if None in ids:
        errs.append('operation without operationId')
    dup = {i for i in ids if ids.count(i) > 1}
    if dup:
        errs.append(f'duplicate operationIds {sorted(dup)}')

    # Collect every schema (components + inline) and every example.
    schemas = [(f'components/schemas/{n}', s) for n, s in doc['components']['schemas'].items()]
    examples = []

    def content_of(where, content):
        for ct, c in (content or {}).items():
            if 'schema' in c:
                schemas.append((f'{where} {ct}', c['schema']))
                for name, ex in (c.get('examples') or {}).items():
                    examples.append((f'{where} {ct} example {name}', c['schema'], ex['value']))

    def headers_of(where, headers):
        for h, hd in (headers or {}).items():
            hd = resolve(doc, hd)
            if 'schema' in hd:
                schemas.append((f'{where} header {h}', hd['schema']))

    for n, r in doc['components'].get('responses', {}).items():
        content_of(f'components/responses/{n}', r.get('content'))
        headers_of(f'components/responses/{n}', r.get('headers'))
    for n, h in doc['components'].get('headers', {}).items():
        schemas.append((f'components/headers/{n}', h['schema']))
    for n, prm in doc['components'].get('parameters', {}).items():
        schemas.append((f'components/parameters/{n}', prm['schema']))
    for pth, m, op in ops:
        where = f'{m.upper()} {pth}'
        for prm in op.get('parameters', []):
            prm = resolve(doc, prm)
            schemas.append((f'{where} param {prm["name"]}', prm['schema']))
        content_of(f'{where} request', (op.get('requestBody') or {}).get('content'))
        for code, r in op['responses'].items():
            if '$ref' not in r:  # referenced responses are checked once, above
                content_of(f'{where} {code}', r.get('content'))
                headers_of(f'{where} {code}', r.get('headers'))

    for where, s in schemas:
        try:
            Draft202012Validator.check_schema(s)
        except Exception as e:  # noqa: BLE001 - report any schema error
            errs.append(f'schema {where}: {getattr(e, "message", e)!s:.120}')
    for where, s, value in examples:
        if '$ref' in s and not s['$ref'].startswith('#/'):
            continue  # external schema (instruction v1) has its own fixture suite
        e = next(iter(validator(s).iter_errors(value)), None)
        if e:
            errs.append(f'{where}: {e.message:.120}')

    # Conventions.
    if doc.get('security') != [{'session': []}]:
        errs.append('root security must be [{session: []}]')
    for pth, m, op in ops:
        where = f'{op.get("operationId")} ({m.upper()} {pth})'
        codes = set(op['responses'])
        sec = op.get('security')
        if pth.startswith('/ingress/'):
            if sec != []:
                errs.append(f'{where}: ingress must declare security: []')
            if codes & {'401', '403'} or '404' not in codes:
                errs.append(f'{where}: ingress must use the empty 404, never 401/403')
        else:
            if sec is None and '401' not in codes:
                errs.append(f'{where}: session operation without 401')
            if (op.get('requestBody') or op.get('parameters')) and '400' not in codes:
                errs.append(f'{where}: operation with input but no 400')
            if pth.startswith('/api/v1/') and m in STATE_CHANGING and '403' not in codes:
                errs.append(f'{where}: state-changing /api/v1 operation without 403 (Origin check)')
        if '500' not in codes:
            errs.append(f'{where}: no 500')
        step_up = op.get('x-step-up')
        if step_up is not None:
            if step_up not in (True, 'conditional'):
                errs.append(f'{where}: x-step-up must be true or "conditional"')
            if (step_up == 'conditional') != isinstance(op.get('x-step-up-when'), str):
                errs.append(f'{where}: x-step-up-when is required exactly when x-step-up is conditional')
            if '403' not in codes:
                errs.append(f'{where}: x-step-up operation without 403')

    print(f'operations: {len(ops)}, schemas checked: {len(schemas)}, examples checked: {len(examples)}')
    print('\n'.join(errs) if errs else 'OPENAPI CHECK OK')
    return 1 if errs else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1], write='--write' in sys.argv[2:]))
