#!/usr/bin/env python3
"""Regenerates src/AllWin.Adapter.Core/Protocol/Schema/ContractSchemas.g.cs from contracts/.

The schemas are embedded as C# constants (not resources) so the NT8 hot source loop, which
compiles only .cs files, gets them too (ADR-0005 N9). A unit test fails on drift.
Usage: python3 plugins/ninjatrader8/tools/gen-contract-schemas.py
"""
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[2]
OUT = HERE.parent / "src/AllWin.Adapter.Core/Protocol/Schema/ContractSchemas.g.cs"
SOURCES = [
    ("AdapterProtocolV1", "contracts/adapter-protocol/v1/messages.schema.json"),
    ("InstructionV1", "contracts/instruction/v1/instruction.schema.json"),
]


def main() -> None:
    lines = [
        "// <auto-generated>",
        "// Generated by plugins/ninjatrader8/tools/gen-contract-schemas.py from contracts/. Do not edit.",
        "// </auto-generated>",
        "namespace AllWin.Adapter.Core.Protocol.Schema",
        "{",
        "    internal static class ContractSchemas",
        "    {",
    ]
    for name, rel in SOURCES:
        text = (REPO / rel).read_text(encoding="utf-8")
        lines.append(f"        /// <summary>Verbatim copy of {rel}.</summary>")
        lines.append(f"        public const string {name}Path = \"{rel}\";")
        lines.append(f"        public const string {name} = @\"" + text.replace('"', '""') + "\";")
    lines += ["    }", "}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
